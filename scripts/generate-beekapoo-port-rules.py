#!/usr/bin/env python3
"""Validate per-manufacturer port rules and compile Rack-independent tables."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'res/Beekapoo/patch-rules'
TARGET = ROOT / 'src/BeekapooPortRules.inc'


def groups(value, ids):
    if not isinstance(value, list):
        raise ValueError('Requirements must be arrays of OR groups')
    for group in value:
        if not isinstance(group, list) or not group:
            raise ValueError('Each OR group must be a nonempty array')
        if any(type(i) is not int or i not in ids for i in group):
            raise ValueError(f'Unknown port in {group}')
        if len(set(group)) != len(group):
            raise ValueError('Duplicate port within requirement group')
    return value


def validate(data):
    if set(data) != {'version', 'manufacturer', 'modules'} or data['version'] != 1:
        raise ValueError('Expected version 1, manufacturer and modules')
    if not isinstance(data['manufacturer'], str) or not data['manufacturer']:
        raise ValueError('Manufacturer must be a plugin slug')
    if not isinstance(data['modules'], dict):
        raise ValueError('Modules must be keyed by model slug')
    for slug, module in data['modules'].items():
        if not slug or set(module) - {'inputs', 'outputs', 'preferredOutputs'}:
            raise ValueError(f'{slug}: unknown module fields')
        ids = {}
        for side in ('inputs', 'outputs'):
            ports = module.get(side, {})
            if not isinstance(ports, dict) or any(not k.isdigit() or str(int(k)) != k for k in ports):
                raise ValueError(f'{slug}: ports must use nonnegative numeric IDs')
            ids[side] = {int(k) for k in ports}
        for side in ('inputs', 'outputs'):
            for port, rule in module.get(side, {}).items():
                allowed = {'label', 'requiresInputs'} | ({'requiresOutputs'} if side == 'inputs' else set())
                if not isinstance(rule, dict) or set(rule) - allowed:
                    raise ValueError(f'{slug}/{side}/{port}: unknown fields')
                if 'label' in rule and not isinstance(rule['label'], str):
                    raise ValueError('Label must be a string')
                groups(rule.get('requiresInputs', []), ids['inputs'])
                groups(rule.get('requiresOutputs', []), ids['outputs'])
                if side == 'inputs' and any(int(port) in g for g in rule.get('requiresInputs', [])):
                    raise ValueError('Input cannot require itself')
        preferred = module.get('preferredOutputs', [])
        if preferred:
            groups([preferred], ids['outputs'])
        elif not isinstance(preferred, list):
            raise ValueError('preferredOutputs must be an array')
        # Input prerequisites are constructive dependencies. Reject cycles,
        # rather than letting a circular pair justify its own existence.
        graph = {int(k): {i for g in v.get('requiresInputs', []) for i in g}
                 for k, v in module.get('inputs', {}).items()}
        def visit(node, active, done):
            if node in active:
                raise ValueError(f'{slug}: circular input requirements')
            if node in done:
                return
            for other in graph.get(node, ()):
                visit(other, active | {node}, done)
            done.add(node)
        done = set()
        for node in graph:
            visit(node, set(), done)


def cpp_groups(value):
    return '{' + ', '.join('{{' + ', '.join(map(str, group)) + '}}' for group in value) + '}'


def generate():
    lines = ['// Generated by scripts/generate-beekapoo-port-rules.py. Do not edit.',
             '// clang-format off',
             'inline const std::map<std::pair<std::string, std::string>, Spec>& portLibrary() {',
             '  static const std::map<std::pair<std::string, std::string>, Spec> rules = {']
    seen = set()
    for path in sorted(SOURCE.glob('*.json')):
        data = json.loads(path.read_text())
        validate(data)
        if data['manufacturer'] in seen:
            raise ValueError('One file per manufacturer')
        seen.add(data['manufacturer'])
        for slug, module in sorted(data['modules'].items()):
            ins = module.get('inputs', {})
            outs = module.get('outputs', {})
            required = {i for r in outs.values() for g in r.get('requiresInputs', []) for i in g}
            # Required signal inputs are filled by the planner, not exposed
            # as spare controls. A manufacturer may omit removed/unused ports.
            controls = []
            all_controls = []
            for key, rule in sorted(ins.items(), key=lambda p: int(p[0])):
                entry = '{' + key + ', ' + cpp_groups(rule.get('requiresInputs', [])) + ', ' + cpp_groups(rule.get('requiresOutputs', [])) + '}'
                all_controls.append(entry)
                if int(key) not in required:
                    controls.append(entry)
            outputs = []
            for key, rule in sorted(outs.items(), key=lambda p: int(p[0])):
                priority = int(int(key) in module.get('preferredOutputs', []))
                outputs.append('{' + key + ', ' + cpp_groups(rule.get('requiresInputs', [])) + ', ' + str(priority) + '}')
            q = lambda s: json.dumps(s, ensure_ascii=True)
            lines.append('    {{' + q(data['manufacturer']) + ', ' + q(slug) + '}, {' + q(slug) + ', {' + ', '.join(controls) + '}, {' + ', '.join(outputs) + '}, {}, {}, {' + ', '.join(all_controls) + '}}},')
    lines += ['  };', '  return rules;', '}', '// clang-format on', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Beek port tables are stale: run scripts/generate-beekapoo-port-rules.py')
    elif not TARGET.exists() or TARGET.read_text() != content:
        TARGET.write_text(content)


if __name__ == '__main__':
    main()
