#pragma once
inline void checkBlunchScanning(rack::plugin::Model* model) {
  using B = ComputerscareBlunch;
  auto require = [](bool ok, const char* why) { if (!ok) throw std::runtime_error(why); };
  auto make = [&]() {
    auto m = std::unique_ptr<B>(static_cast<B*>(model->createModule()));
    m->params[B::LIVE_APPLY_PARAM].setValue(0);
    m->params[B::WAIT_MODE_PARAM].setValue(B::WAIT_IMMEDIATE);
    m->runningLineTexts[0].clear();
    m->sequenceEditorStates[0].text = "[100 200 300]ms\n[400 500]ms\n600ms";
    require(m->commitLine(0, true), "Scan fixture compiles");
    m->params[B::POLY_CHANNELS_PARAM].setValue(1);
    return m;
  };
  auto m = make();
  m->params[B::LINE_SCAN_PARAM].setValue(1);
  m->inputs[B::EXTERNAL_CLOCK_W_INPUT].channels = 1;
  m->inputs[B::EXTERNAL_CLOCK_W_INPUT].setVoltage(5);
  require(m->sequencers[0].activeLine == 0, "Scan voltage alone does not move the line");
  m->handleLineCycleEnd();
  require(m->sequencers[0].activeLine == 1, "Line boundary samples scan voltage");
  m->inputs[B::EXTERNAL_CLOCK_W_INPUT].setVoltage(10);
  require(m->sequencers[0].activeLine == 1, "Line scan holds between boundaries");
  m->handleLineCycleEnd();
  require(m->sequencers[0].activeLine == 2, "10 V selects final line");
  m->inputs[B::EXTERNAL_CLOCK_W_INPUT].setVoltage(-2);
  m->params[B::AUTO_ADVANCE_PARAM].setValue(0);
  m->handleLineCycleEnd();
  require(m->sequencers[0].activeLine == 2, "Line advance Off does not sample scan");
  m->moveToNextLine(false);
  require(m->sequencers[0].activeLine == 0, "Explicit/external advance samples clamped scan");
  m->params[B::BLOCK_SCAN_PARAM].setValue(2);
  m->inputs[B::EXTERNAL_CLOCK_X_INPUT].channels = 1;
  m->inputs[B::EXTERNAL_CLOCK_X_INPUT].setVoltage(10);
  m->advanceActiveProgramStep(m->sequencers[0]);
  require(m->sequencers[0].activeProgramIndex == 2, "Block boundary samples final block");
  m->inputs[B::EXTERNAL_CLOCK_X_INPUT].setVoltage(0);
  m->params[B::AUTO_BLOCK_ADVANCE_PARAM].setValue(0);
  m->advanceActiveProgramStep(m->sequencers[0]);
  require(m->sequencers[0].activeProgramIndex == 2, "Block advance Off holds scan selection");
  m->advanceActiveProgramStep(m->sequencers[0], true);
  require(m->sequencers[0].activeProgramIndex == 0, "External/manual block advance samples scan");
  m->inputs[B::EXTERNAL_CLOCK_X_INPUT].channels = 2;
  m->inputs[B::EXTERNAL_CLOCK_X_INPUT].setVoltage(10, 1);
  m->focusedChannel = 1;
  require(m->scanIndex(B::BLOCK_SCAN_PARAM, 3) == 2, "Poly scan addresses matching channel");
  m->focusedChannel = 0;
  rack::engine::Module::ProcessArgs args; args.sampleRate=48000; args.sampleTime=1.f/48000;
  auto tick = [&](B& module, int samples) { for (int i=0;i<samples;++i) { ++args.frame; module.process(args); } };
  args.frame=0;
  auto timed = make();
  timed->params[B::LINE_SCAN_PARAM].setValue(1);
  timed->inputs[B::EXTERNAL_CLOCK_W_INPUT].channels=1;
  timed->inputs[B::EXTERNAL_CLOCK_W_INPUT].setVoltage(5);
  tick(*timed, 24000);
  require(timed->sequencers[0].activeLine==0,"Automatic scan waits for all blocks in the line");
  tick(*timed, 6000);
  require(timed->sequencers[0].activeLine==1,"Automatic scan samples after the completed line");
  auto external = make();
  external->params[B::AUTO_BLOCK_ADVANCE_PARAM].setValue(4); // External Y
  external->params[B::BLOCK_SCAN_PARAM].setValue(2); // Scan X
  external->inputs[B::EXTERNAL_CLOCK_X_INPUT].channels=1;
  external->inputs[B::EXTERNAL_CLOCK_X_INPUT].setVoltage(10);
  external->inputs[B::EXTERNAL_CLOCK_Y_INPUT].channels=1;
  tick(*external, 10000);
  require(external->sequencers[0].activeProgramIndex==0,"External block scan holds across natural block completions");
  external->inputs[B::EXTERNAL_CLOCK_Y_INPUT].setVoltage(10);
  tick(*external,1);
  require(external->sequencers[0].activeProgramIndex==2,"External advance edge samples block scan source");
  auto total = make();
  total->sequenceEditorStates[0].text="[100 200]ms#0.1s 400ms";
  total->commitLine(0,true);
  total->params[B::AUTO_BLOCK_ADVANCE_PARAM].setValue(0);
  total->params[B::BLOCK_SCAN_PARAM].setValue(2);
  total->inputs[B::EXTERNAL_CLOCK_X_INPUT].channels=1;
  total->inputs[B::EXTERNAL_CLOCK_X_INPUT].setVoltage(10);
  tick(*total,16000);
  require(total->sequencers[0].activeProgramIndex<2,"Timed groups do not resample scan with block advance Off");
  auto live = make();
  live->params[B::LIVE_APPLY_PARAM].setValue(1);
  live->params[B::WAIT_MODE_PARAM].setValue(B::WAIT_NEXT_VISIT);
  live->sequencers[0].clockPhase = .37f;
  live->sequenceEditorStates[0].text = "[100 200 300]ms\n[410 510]ms\n600ms";
  live->inspectFocusedLine(1, false);
  require(live->sequencers[0].activeLine == 0 && live->sequencers[0].clockPhase == .37f && live->runningLineTexts[0][1] == "[400 500]ms", "Typing another line preserves current transport and Now");
  require(live->channelHasNext(0), "Auto-staged edits wait for the chosen Next visit boundary");
  tick(*live,1);
  require(live->sequencers[0].activeLine == 0,"Audio processing does not apply live edits immediately");
  live->handleLineCycleEnd();
  require(live->sequencers[0].activeLine == 1 && live->sequencers[0].activeLineText == "[410 510]ms", "Next visit accepts live-edited line");
  live->params[B::AUTO_ADVANCE_PARAM].setValue(0);
  live->sequenceEditorStates[0].text = "[100 200 300]ms\n[420 520]ms\n600ms";
  live->inspectFocusedLine(1, false);
  require(live->sequencers[0].activeLineText == "[410 510]ms", "Current visit remains unchanged");
  auto* data = live->dataToJson();
  auto restored = make(); restored->dataFromJson(data); json_decref(data);
  require(restored->channelHasNext(0), "Auto-staged edits persist");
  live->handleLineCycleEnd();
  require(live->sequencers[0].activeLineText == "[420 520]ms", "Held line applies on next repetition");
  auto autoImmediate = make();
  autoImmediate->params[B::LIVE_APPLY_PARAM].setValue(1);
  autoImmediate->sequenceEditorStates[0].text="[100 200 300]ms\n700ms\n600ms";
  autoImmediate->inspectFocusedLine(1,false);
  require(!autoImmediate->channelHasNext(0) && autoImmediate->runningLineTexts[0][1]=="700ms" && autoImmediate->sequencers[0].activeLine==0,"Auto-stage obeys Immediate without redirecting playback");
  auto autoPage = make();
  autoPage->params[B::LIVE_APPLY_PARAM].setValue(1);
  autoPage->params[B::WAIT_MODE_PARAM].setValue(B::WAIT_PAGE);
  autoPage->sequenceEditorStates[0].text="[100 200 300]ms\n710ms\n600ms";
  autoPage->inspectFocusedLine(1,false);
  autoPage->handleLineCycleEnd();
  require(autoPage->sequencers[0].activeLineText=="[400 500]ms" && autoPage->channelHasNext(0),"Auto-stage obeys Page instead of forcing Next visit");
  autoPage->handleLineCycleEnd();autoPage->handleLineCycleEnd();autoPage->handleLineCycleEnd();
  require(autoPage->sequencers[0].activeLineText=="710ms","Page boundary activates auto-staged edits");
  auto immediate = make();
  immediate->sequencers[0].clockPhase=.42f;
  immediate->sequenceEditorStates[0].text="[100 200 300]ms\n900ms\n600ms";
  immediate->executeLine(1,false,true);
  require(immediate->sequencers[0].activeLine==0 && immediate->sequencers[0].clockPhase==.42f && immediate->runningLineTexts[0][1]=="900ms", "Immediate stage of another line never restarts playback");
  auto overview = make();
  overview->runningLineTexts[0].clear();
  overview->sequenceEditorStates[0].text="120bpm";
  overview->commitLine(0,true);
  overview->params[B::LIVE_APPLY_PARAM].setValue(1);
  overview->params[B::WAIT_MODE_PARAM].setValue(B::WAIT_NEXT_VISIT);
  overview->refreshChannelsEditorState(true);
  auto row=getLineInfo(overview->channelsEditorState.text,0);
  overview->channelsEditorState.text.replace(row.begin,row.end-row.begin,"130bpm");
  overview->syncChannelsEditorEdit(0);
  require(overview->channelHasNext(0) && overview->sequencers[0].activeLineText=="120bpm", "All-view live edits stage without interrupting playback");
  auto stage = make(); stage->params[B::WAIT_MODE_PARAM].setValue(B::WAIT_NEXT_VISIT);
  stage->sequenceEditorStates[0].text = "[100 200 300]ms\n800ms\n600ms";
  require(stage->executeLine(1, false, true), "Stage-only line validates");
  require(stage->sequencers[0].activeLine == 0 && stage->pendingFormulas[0].line == -1, "Stage line does not request a jump");
  stage->handleLineCycleEnd();
  require(stage->sequencers[0].activeLineText == "800ms", "Stage line activates on next visit");
  require(!stage->handleLayerKey(GLFW_KEY_F6, 0, GLFW_PRESS) && stage->visibleLayer() == B::DRAFT, "F6 no longer changes formula view");
  std::puts("Blunch boundary-sampled line/block scan, noninterrupting staging, persistence and F6 removal passed");
}
